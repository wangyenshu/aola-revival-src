#!/usr/bin/env python3
"""Generate the tables of the rebuilt pet/pmservice.

The January 2013 PMService (pet/pmservice v130124) is lost; the live file is a
later rework on later interfaces. The 2013 client asks it for
mmo.interfaces.pet.pm.data.PMCustomData: four maps of rows (PMData, PMExp,
PMAttDef, PMSkill) whose columns are the titles of the 2013 PMExcelMap. This
writes those rows from the emulator's tables, revival/pmdata.json
(tools/gen_pmdata.py, itself from the later file's PMDataList, whose rows have
the same columns), as an ActionScript class:

  tools/gen_pmservice.py --pmdata rebuild/static/www.9aola.com/revival/pmdata.json \\
      --out rebuild/gen/pmservice

Columns pmdata.json does not keep (height, weight, 特性, catch details beyond
the two rates, machine and AI skills, recommendations) are empty strings, as
an empty cell of the original table reads.
"""
from __future__ import annotations

import argparse
import json
import os

PMDATA_COLUMNS = 37
SKILL_COLUMNS = 28
# The attribute table's cells as the original writes them (PMAttDef.getMultipleValue).
CELL = {0.5: "1/2", 2: "2", 3: "3", 0: "-1"}


def esc(v) -> str:
    return json.dumps(str(v), ensure_ascii=False)


def row(cells) -> str:
    return "[" + ",".join(esc(c) for c in cells) + "]"


def pm_row(rid: str, sp: dict) -> list:
    r = [""] * PMDATA_COLUMNS
    r[0] = rid
    r[1] = sp["n"]
    for i, v in enumerate(sp.get("s") or [0] * 6):
        r[4 + i] = v
    for i, v in enumerate(sp.get("ev") or [0] * 6):
        r[10 + i] = v
    t = sp.get("t") or [0, 0]
    r[16], r[17] = t[0], t[-1]
    r[20] = sp.get("bx", 0)
    r[21] = sp.get("xt") or "0"
    c = sp.get("c") or ["", ""]
    r[24], r[25] = c[0], c[-1]
    r[26] = sp.get("evo") or ""
    r[29] = "#".join(f"{lv}-{sk}" for lv, sk in sp.get("learn") or [])
    return r


def skill_row(sid: str, s: dict) -> list:
    r = [""] * SKILL_COLUMNS
    r[0] = sid
    r[2] = s.get("old") or ""
    r[3] = s.get("n") or ""
    r[5] = r[6] = s.get("d") or ""
    r[7] = s.get("p", 0)
    r[8] = s.get("acc", 100)
    r[9] = s.get("pp", 20)
    r[10] = s.get("pri", 0)
    r[11] = s.get("t", 0)
    r[12] = s.get("k", 0)
    r[26] = s.get("p1", s.get("p", 0))
    return r


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pmdata", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    d = json.load(open(a.pmdata, encoding="utf-8"))
    attrs = sorted(d["chart"], key=int)
    width = max(int(k) for k in attrs) + 1
    pms = [f"         {row(pm_row(rid, d['species'][rid]))}" for rid in sorted(d["species"], key=int)]
    skills = [f"         {row(skill_row(sid, d['skills'][sid]))}" for sid in sorted(d["skills"], key=int)]
    chart = []
    for k in attrs:
        cells = [CELL.get(d["chart"][k].get(str(i), 1), "") for i in range(width)]
        chart.append(f"         {esc(k)}:{row(cells)}")
    exp = [f"         {esc(k)}:[{','.join(str(int(v)) for v in d['exp'][k])}]" for k in sorted(d["exp"], key=int)]
    levels = max(len(v) for v in d["exp"].values())

    def maker(name: str, cls: str, n: int, conv: str = "") -> str:
        # The row classes take their cells as arguments (...rest), so each is passed by itself.
        args = ", ".join(f"{conv}(r[{i}])" if conv else f"r[{i}]" for i in range(n))
        return f"""      public static function {name}(r:Array):{cls}
      {{
         return new {cls}({args});
      }}
"""

    makers = (maker("newPM", "PMData", PMDATA_COLUMNS) + "\n" + maker("newSkill", "PMSkill", SKILL_COLUMNS) + "\n"
              + maker("newAttDef", "PMAttDef", width) + "\n" + maker("newExp", "PMExp", levels, "String"))
    out = f"""package mmo.pm.service
{{
   import mmo.interfaces.pet.pm.data.custom.PMAttDef;
   import mmo.interfaces.pet.pm.data.custom.PMData;
   import mmo.interfaces.pet.pm.data.custom.PMExp;
   import mmo.interfaces.pet.pm.data.custom.PMSkill;

   /** GENERATED by tools/gen_pmservice.py from revival/pmdata.json: the rows of the 2013 PMCustomData. */
   public class PMTables
   {{
      /** Columns of a PMData row and of a PMSkill row; levels of a PMExp row. */
      public static const PM_COLUMNS:int = {PMDATA_COLUMNS};
      public static const SKILL_COLUMNS:int = {SKILL_COLUMNS};
      public static const EXP_LEVELS:int = {levels};

      /** PMData rows (PMExcelMap PMData_Titles: 种族Id, 名称, 身高, 体重, HP … 推荐技能). */
      public static const pms:Array = [
{(","+chr(10)).join(pms)}
      ];

      /** PMSkill rows (PMExcelMap Skill_Titles: 技能Id, 英文名称, 原中文名称, 新中文名称 … 双倍威力). */
      public static const skills:Array = [
{(","+chr(10)).join(skills)}
      ];

      /** PMAttDef rows by attacking attribute: the cell for each defending attribute. */
      public static const attDef:Object = {{
{(","+chr(10)).join(chart)}
      }};

      /** PMExp rows by experience type: the experience at level 1, 2, … */
      public static const exp:Object = {{
{(","+chr(10)).join(exp)}
      }};

{makers}   }}
}}
"""
    path = os.path.join(a.out, "mmo", "pm", "service")
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, "PMTables.as"), "w", encoding="utf-8") as f:
        f.write(out)
    print(f"{len(pms)} 亚比, {len(skills)} skills, {len(chart)} attributes, {len(exp)} experience types -> {path}/PMTables.as")


if __name__ == "__main__":
    main()
