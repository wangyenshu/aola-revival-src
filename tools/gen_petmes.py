#!/usr/bin/env python3
"""Generate the data of the rebuilt pet/petskillmesservice.

The January 2013 PetSkillMesService is lost (the live one is a 2026 rework on
the later IPMService). Its answers (a 亚比's name, attribute and evolution
line, a skill's name, power, hit rate and PP, the experience table) come from
the same tables the emulator reads, revival/pmdata.json (tools/gen_pmdata.py),
written as an ActionScript class so the module needs nothing at run time.

  tools/gen_petmes.py --pmdata rebuild/static/www.9aola.com/revival/pmdata.json \\
      --out rebuild/gen/petmes
"""
from __future__ import annotations

import argparse
import json
import os


def esc(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pmdata", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    d = json.load(open(a.pmdata, encoding="utf-8"))
    lines = []
    for rid in sorted(d["species"], key=int):
        sp = d["species"][rid]
        t = sp.get("t") or [0, 0]
        # [name, attribute, attribute2, evolution "level-race#…", exp type]
        lines.append(f'         "{rid}":[{esc(sp["n"])},{int(t[0])},{int(t[-1])},{esc(sp.get("evo") or ("0-" + rid))},{esc(str(sp.get("xt") or ""))}]')
    skills = []
    for sid in sorted(d["skills"], key=int):
        s = d["skills"][sid]
        # [name, power, hit rate, PP, attribute, kind, description]
        skills.append(f'         "{sid}":[{esc(s["n"])},{int(s.get("p") or 0)},{int(s.get("acc") or 0)},{int(s.get("pp") or 0)},{int(s.get("t") or 0)},{int(s.get("k") or 0)},{esc(s.get("d") or "")}]')
    exp = [f'         "{k}":[{",".join(str(int(x)) for x in v)}]' for k, v in sorted(d["exp"].items(), key=lambda kv: int(kv[0]))]
    body = (
        "package mmo.pet.petskillmessage\n{\n"
        "   /** GENERATED by tools/gen_petmes.py from revival/pmdata.json. */\n"
        "   public class PetMesData\n   {\n"
        "      /** race -> [name, attribute, attribute2, evolution, exp type] */\n"
        "      public static const pets:Object = {\n" + ",\n".join(lines) + "\n      };\n\n"
        "      /** skill -> [name, power, hit rate, PP, attribute, kind, description] */\n"
        "      public static const skills:Object = {\n" + ",\n".join(skills) + "\n      };\n\n"
        "      /** exp type -> experience to reach each level */\n"
        "      public static const exp:Object = {\n" + ",\n".join(exp) + "\n      };\n"
        "   }\n}\n"
    )
    dest = os.path.join(a.out, "mmo", "pet", "petskillmessage")
    os.makedirs(dest, exist_ok=True)
    with open(os.path.join(dest, "PetMesData.as"), "w", encoding="utf-8") as f:
        f.write(body)
    print(f"{len(lines)} 亚比, {len(skills)} skills -> {dest}/PetMesData.as")


if __name__ == "__main__":
    main()
