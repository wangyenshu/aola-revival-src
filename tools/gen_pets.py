#!/usr/bin/env python3
"""Generate the 亚比 (pet) species data of the revival from the later client.

The 2013 species table is lost, but the later client keeps two tables whose
format the 2013 classes still read:

  pet/petdictionarydata  PetDictionaryData: new PetDictionaryDataItem(id, name,
                         height, weight, defAttr, attAttr, evolutionLevel, new,
                         rare, area, getWay, food, intro, serie, form, ...) -
                         the 2013 PetDictionaryDataItem takes the same varargs
  pet/pmservice          PMSearchDataList: [id, name, attr, attr2, evolutions,
                         later evolutions, skill names, ...]

Kept: species up to the highest id whose icon peticon/peticon<id>.swf is an
era file in mirror/ (uploaded by 25 Jan 2013), i.e. the 亚比 that existed then. Written (百田's
data, so into rebuild/gen and the rebuilt root, not git):

  <gen>/mmo/pet/petdictionarydata/PetDictionaryData.as   for the rebuilt module
  <rebuilt>/www.9aola.com/revival/pets.json               for the server:
      {"<id>": {"n": name, "a": attribute, "e": evolution level or 0,
                "next": id it evolves into or 0, "sk": [skill names]}}

  tools/gen_pets.py --dict .../PetDictionaryData.as --search .../PMSearchDataList.as \\
      --mirror mirror --gen rebuild/gen/petdict --json rebuilt/www.9aola.com/revival/pets.json
"""
from __future__ import annotations

import argparse
import json
import os
import re


def era_ids(mirror: str) -> set[int]:
    out = set()
    for f in os.listdir(os.path.join(mirror, "www.9aola.com", "peticon")):
        m = re.match(r"peticon(\d+)\.swf", f)
        if m:
            out.add(int(m.group(1)))
    return out


def parse_json_array(s: str):
    try:
        return json.loads(s)
    except Exception:
        return None


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dict", required=True)
    ap.add_argument("--search", required=True)
    ap.add_argument("--mirror", required=True)
    ap.add_argument("--gen", required=True)
    ap.add_argument("--json", required=True)
    a = ap.parse_args(argv)
    era = era_ids(a.mirror)

    dict_lines = {}
    for line in open(a.dict, encoding="utf-8"):
        m = re.match(r'\s*"(\d+)":(new PetDictionaryDataItem\(.*\)),?\s*$', line)
        if m:
            dict_lines[int(m.group(1))] = m.group(2)
    search = {}
    for line in open(a.search, encoding="utf-8"):
        m = re.match(r'\s*"(\d+)":(\[.*\]),?\s*$', line)
        if m:
            arr = parse_json_array(m.group(2))
            if arr:
                search[int(m.group(1))] = arr

    # Species ids were handed out in order; everything up to the newest era icon existed by then
    # (some early icons were redrawn later, e.g. 兔小子's peticon1 in 2020).
    # (ids of 10000 and up are special forms with their own numbering: ignored for the cut.)
    top = max((i for i in era if i < 10000), default=0)
    keep = sorted(i for i in dict_lines if i <= top or i in era)
    pkg = os.path.join(a.gen, "mmo", "pet", "petdictionarydata")
    os.makedirs(pkg, exist_ok=True)
    rows = ",\n".join(f'         "{i}":{dict_lines[i]}' for i in keep)
    open(os.path.join(pkg, "PetDictionaryData.as"), "w", encoding="utf-8").write(
        "package mmo.pet.petdictionarydata\n{\n   import mmo.interfaces.pet.data.PetDictionaryDataItem;\n\n"
        "   /** GENERATED by tools/gen_pets.py: the 亚比 that existed by 25 Jan 2013 (era peticon files). */\n"
        "   public class PetDictionaryData\n   {\n      public static const data:Object = {\n" + rows + "\n      };\n   }\n}\n")

    names = {}
    for i in keep:
        args = re.findall(r'"((?:[^"\\]|\\.)*)"', dict_lines[i])
        names[i] = args[1] if len(args) > 1 else ""
    pets = {}
    for i in keep:
        args = re.findall(r'"((?:[^"\\]|\\.)*)"', dict_lines[i])
        evo = args[6] if len(args) > 6 else "-"
        m = re.match(r"(\d+)级", evo)
        s = search.get(i, [])
        attr = int(s[2]) if len(s) > 2 and str(s[2]).isdigit() else 0
        skills = s[6] if len(s) > 6 and isinstance(s[6], list) else []
        nxt = 0
        if m and (i + 1) in names:
            nxt = i + 1  # the dictionary lists each line's next form right after it
        pets[str(i)] = {"n": names[i], "a": attr, "e": int(m.group(1)) if m else 0, "next": nxt, "sk": skills[:12]}
    os.makedirs(os.path.dirname(a.json), exist_ok=True)
    json.dump(pets, open(a.json, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print(f"{len(keep)} era species of {len(dict_lines)} -> {pkg}, {a.json}")


if __name__ == "__main__":
    main()
