#!/usr/bin/env python3
"""Generate the scene clothes (walking figures) of the 亚比 the 2013 tables do not know.

The 2013 interfaces' PetClothesMap (亚比 -> scene clothes) and materialdata's ClothesData /
ClothesPartsDatas (the clothes and their parts) end with the 亚比 of January 2013. The
revival's 亚比 go further (tools/gen_pets.py --top): their clothes come from the later
client (control's PetClothesMap, the later library/materialdata's ClothesData and
ClothesPartsDatas, decompiled with FFDec). Kept: those of the species of revival/pets.json
that the 2013 map lacks and whose skin file is in game/. Written (百田's data, as
rebuild/gen/petdict):

  rebuild/gen/petfollow/mmo/petfollow/PetClothesExtra.as
      ROWS: [race, clothes id, name, part, position, movie, sides, frames, file]

which the rebuilt pet/petfollow adds to the 2013 clothes service when one of them follows.

  tools/gen_petclothes.py --map <later>/mmo/interfaces/pet/data/PetClothesMap.as \\
      --era-map <2013>/mmo/interfaces/pet/data/PetClothesMap.as \\
      --clothes <later materialdata>/mmo/materialdata/ClothesData.as \\
      --parts <later materialdata>/mmo/materialdata/ClothesPartsDatas.as \\
      --pets rebuild/static/www.9aola.com/revival/pets.json --game game \\
      --out rebuild/gen/petfollow
"""
from __future__ import annotations

import argparse
import json
import os
import re


def clothes_map(path: str) -> dict[int, int]:
    return {int(a): int(b) for a, b in re.findall(r"map\[(\d+)\]\s*=\s*(\d+);", open(path, encoding="utf-8").read())}


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for k in ("--map", "--era-map", "--clothes", "--parts", "--pets", "--game", "--out"):
        ap.add_argument(k, required=True)
    a = ap.parse_args(argv)
    later, era = clothes_map(a.map), clothes_map(a.era_map)
    parts = open(a.parts, encoding="utf-8").read()
    names = open(a.clothes, encoding="utf-8").read()
    skins = {f.split("%3F")[0][:-4] for f in os.listdir(os.path.join(a.game, "www.9aola.com", "skin"))}
    pets = json.load(open(a.pets, encoding="utf-8"))
    rows = []
    for k in sorted(pets, key=int):
        race = int(k)
        if race in era or race not in later:
            continue
        c = later[race]
        m = re.search(r'"%d":\[\[new ClothesParts\("(\w+)",SkinPosInfo\.(\w+),SkinInfoFactory\.(\w+),ClothesSideTypes\.(\w+),"(\d*)"\)\],"(\w+)"\]' % c, parts)
        if not m or m.group(6) not in skins:
            continue
        n = re.search(r'"%d":new Clothes\(%d,"([^"]*)"' % (c, c), names)
        part, pos, movie, sides, frames, file = m.groups()
        rows.append(f'[{race},{c},"{n.group(1) if n else ""}","{part}","{pos}","{movie}","{sides}","{frames}","{file}"]')
    pkg = os.path.join(a.out, "mmo", "petfollow")
    os.makedirs(pkg, exist_ok=True)
    body = ",\n         ".join(rows)
    open(os.path.join(pkg, "PetClothesExtra.as"), "w", encoding="utf-8").write(
        "package mmo.petfollow\n{\n"
        "   /** GENERATED by tools/gen_petclothes.py: the scene clothes of the 亚比 after the 2013 tables. */\n"
        "   public class PetClothesExtra\n   {\n"
        "      /** [race, clothes id, name, part, SkinPosInfo, SkinInfoFactory, ClothesSideTypes, frames, file] */\n"
        "      public static const ROWS:Array = [\n         " + body + "\n      ];\n   }\n}\n")
    print(f"{len(rows)} 亚比 with later scene clothes -> {pkg}")


if __name__ == "__main__":
    main()
